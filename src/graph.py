class Neo4jGraph:
    """Thin wrapper over the official neo4j driver."""

    def __init__(self, uri: str, user: str, password: str) -> None:
        from neo4j import GraphDatabase

        self.driver = GraphDatabase.driver(uri, auth=(user, password), notifications_min_severity="OFF")
        self.driver.verify_connectivity()

    def close(self) -> None:
        self.driver.close()

    def run(self, cypher: str, **params: Any) -> list[dict]:
        records, _, _ = self.driver.execute_query(cypher, params)
        return [record.data() for record in records]

    def reset(self) -> None:
        """Delete every node, relationship and constraint (bench_kg.py calls this before build_graph)."""
        self.run("MATCH (n) DETACH DELETE n")
        for row in self.run("SHOW CONSTRAINTS YIELD name RETURN name"):
            self.run(f"DROP CONSTRAINT `{row['name']}` IF EXISTS")

    def stats(self) -> dict[str, int]:
        nodes = self.run("MATCH (n) RETURN count(n) AS n")[0]["n"]
        rels = self.run("MATCH ()-[r]->() RETURN count(r) AS n")[0]["n"]
        return {"nodes": nodes, "relationships": rels}

    def seed_facts(self, question: str, doc_ids: list[str], skip_labels: tuple[str, ...] = (),
                   limit: int = 60) -> tuple[list[str], list[str]]:
        """Ontology-independent first step: seed nodes + their 1-hop edges as text facts.

        Seeds = nodes whose `doc_id` is in doc_ids, or whose `name`/`aliases` appear in the question.
        Returns (seed elementIds, facts). Nodes with a label in skip_labels are left out of the facts.
        """
        seeds = self.run(
            """
            MATCH (n)
            WHERE n.doc_id IN $doc_ids
               OR (n.name IS :: STRING AND size(n.name) >= 3 AND toLower($q) CONTAINS toLower(n.name))
               OR any(a IN coalesce(n.aliases, []) WHERE size(a) >= 3 AND toLower($q) CONTAINS toLower(a))
            RETURN elementId(n) AS id
            """,
            q=question, doc_ids=doc_ids,
        )
        seed_ids = [row["id"] for row in seeds]
        edges = self.run(
            """
            MATCH (s)-[r]-(m)
            WHERE elementId(s) IN $ids
              AND none(l IN labels(s) + labels(m) WHERE l IN $skip)
            WITH DISTINCT r LIMIT $limit
            WITH startNode(r) AS a, r, endNode(r) AS b
            RETURN labels(a)[0] AS a_label, coalesce(a.name, a.id) AS a_name, type(r) AS rel,
                   properties(r) AS props, labels(b)[0] AS b_label, coalesce(b.name, b.id) AS b_name
            """,
            ids=seed_ids, skip=list(skip_labels), limit=limit,
        )
        facts = []
        for e in edges:
            props = ", ".join(f"{k}: {v}" for k, v in e["props"].items() if v)
            facts.append(f"({e['a_label']}: {e['a_name']}) -[{e['rel']}{' {' + props + '}' if props else ''}]-> "
                         f"({e['b_label']}: {e['b_name']})")
        return seed_ids, facts

    # ---------------------------------------------------------------- HINT — suggested ontology: writes

    def suggested_constraints(self) -> None:
        for label, key in [("Article", "id"), ("Clause", "id"), ("Crime", "name"), ("Case", "name"),
                           ("Substance", "name"), ("Person", "name"), ("Location", "name")]:
            self.run(f"CREATE CONSTRAINT IF NOT EXISTS FOR (n:{label}) REQUIRE n.{key} IS UNIQUE")

    def add_law_article(self, article: dict) -> None:
        self.run(
            """
            MERGE (a:Article {id: $id}) SET a.title = $title, a.law = $law, a.doc_id = $doc_id
            FOREACH (crime IN CASE WHEN $crime IS NULL THEN [] ELSE [$crime] END |
                MERGE (c:Crime {name: crime}) MERGE (a)-[:DEFINES]->(c))
            WITH a
            UNWIND $clauses AS clause
            MERGE (cl:Clause {id: clause.id})
              SET cl.number = clause.number, cl.penalty = clause.penalty, cl.text = clause.text, cl.doc_id = $doc_id
            MERGE (a)-[:HAS_CLAUSE]->(cl)
            FOREACH (s IN clause.substances | MERGE (sub:Substance {name: s}) MERGE (cl)-[:MENTIONS]->(sub))
            """,
            **article,
        )

    def add_news_case(self, case: dict, doc: Document) -> None:
        self.run(
            """
            MERGE (k:Case {name: $name})
              SET k.summary = $summary, k.date = $date, k.doc_id = $doc_id, k.source_title = $title
            FOREACH (loc IN CASE WHEN $location = '' THEN [] ELSE [$location] END |
                MERGE (l:Location {name: loc}) MERGE (k)-[:LOCATED_IN]->(l))
            FOREACH (crime IN $charges | MERGE (c:Crime {name: crime}) MERGE (k)-[:CHARGED_WITH]->(c))
            FOREACH (s IN $substances | MERGE (sub:Substance {name: s.name}) MERGE (k)-[r:INVOLVES]->(sub)
                SET r.amount = s.amount)
            FOREACH (p IN $people | MERGE (person:Person {name: p.name})
                SET person.aliases = coalesce(p.aliases, [])
                MERGE (person)-[r:INVOLVED_IN]->(k) SET r.role = p.role, r.charge = p.charge, r.sentence = p.sentence)
            """,
            name=case.get("name") or doc.metadata.get("title", doc.id),
            summary=case.get("summary", ""), date=case.get("date", ""), location=case.get("location", ""),
            charges=case.get("charges", []), people=[p for p in case.get("people", []) if p.get("name")],
            substances=[s for s in case.get("substances", []) if s.get("name")],
            doc_id=doc.id, title=doc.metadata.get("title", ""),
        )

    # ---------------------------------------------------------------- KG-3

    def context(self, question: str, doc_ids: list[str], max_facts: int = 60) -> list[str]:
        """Graph facts for a question: seeds + 1 hop, then the legal basis of every case reached."""
        if max_facts <= 0:
            return []
        seed_ids, edges = self.seed_facts(question, doc_ids, skip_labels=("Clause",), limit=max_facts)
        quantities = [number.replace(",", ".") + unit.lower() for number, unit in
                      re.findall(r"(\d+(?:[.,]\d+)?)\s*(kg|gam)\b", question, re.IGNORECASE)]
        cases = self.run(
            """MATCH (k:Case)
            WHERE elementId(k) IN $ids
               OR EXISTS { MATCH (s)--(k) WHERE elementId(s) IN $ids }
               OR any(amount IN $amounts WHERE
                      replace(toLower(k.name + ' ' + coalesce(k.summary, '')), ' ', '') CONTAINS amount)
            RETURN elementId(k) AS id, k.name AS name, k.summary AS summary, k.doc_id AS doc_id
            ORDER BY k.doc_id, k.name""", ids=seed_ids, amounts=quantities,
        )
        named = self.run(
            """MATCH (p:Person)-[:INVOLVED_IN]->(k:Case)
            WHERE (size(p.name) >= 3 AND toLower($q) CONTAINS toLower(p.name))
               OR any(alias IN coalesce(p.aliases, []) WHERE size(alias) >= 3
                      AND toLower($q) CONTAINS toLower(alias))
            RETURN DISTINCT elementId(k) AS id""", q=question,
        )
        named_ids = {row['id'] for row in named}
        if named_ids:
            cases = [case for case in cases if case['id'] in named_ids]
        case_ids = [case["id"] for case in cases]
        facts = [f"[{case['doc_id']}] Vụ việc '{case['name']}': {case['summary']}" for case in cases]
        people = self.run(
            """MATCH (p:Person)-[r:INVOLVED_IN]->(k:Case) WHERE elementId(k) IN $ids
            RETURN p.name AS name, p.aliases AS aliases, k.name AS case_name, k.doc_id AS doc_id,
                   r.role AS role, r.sentence AS sentence, r.charge AS charge
            ORDER BY name, doc_id""", ids=case_ids,
        )
        person_facts = []
        for person in people:
            fact = (f"[{person['doc_id']}] {person['name']}: vai trò {person['role']}; "
                    f"mức án {person['sentence'] or 'chưa có trong nguồn'}; "
                    f"tội danh {person['charge'] or 'chưa rõ'}; vụ '{person['case_name']}'.")
            if any(name and name.lower() in question.lower()
                   for name in [person['name']] + (person['aliases'] or [])):
                facts.insert(0, fact)
            else:
                person_facts.append(fact)
        # Basic clause + substance clauses, as in the guide. A maximum-penalty question needs all clauses.
        all_penalties = any(term in question.lower() for term in ("tối đa", "cao nhất"))
        clauses = self.run(
            """MATCH (k:Case)-[:CHARGED_WITH]->(:Crime)<-[:DEFINES]-(a:Article)-[:HAS_CLAUSE]->(cl:Clause)
            WHERE elementId(k) IN $ids AND
              ($all OR cl.number = 1 OR EXISTS { MATCH (k)-[:INVOLVES]->(:Substance)<-[:MENTIONS]-(cl) })
            RETURN DISTINCT a.id AS article_id, a.title AS title, cl.number AS number, cl.text AS text,
                   [(k)-[:INVOLVES]->(s:Substance) | s.name] AS substances
            ORDER BY article_id, number""", ids=case_ids, all=all_penalties,
        )
        # Also support direct law questions, including definitions in the PCMT law (no Crime node).
        direct = self.run(
            """MATCH (a:Article)-[:HAS_CLAUSE]->(cl:Clause)
            WHERE (a.id IN $articles OR ($pcmt AND a.law = 'Luật PCMT')
                   OR (NOT $named AND (elementId(a) IN $ids
                       OR EXISTS { MATCH (a)-[:HAS_CLAUSE]->(seed:Clause) WHERE elementId(seed) IN $ids })))
              AND ($all OR NOT EXISTS { MATCH (a)-[:DEFINES]->() } OR cl.number = 1
                   OR EXISTS { MATCH (cl)-[:MENTIONS]->(s:Substance) WHERE s.name IN $substances })
            RETURN DISTINCT a.id AS article_id, a.title AS title, cl.number AS number, cl.text AS text
            ORDER BY article_id, number""", ids=seed_ids,
            articles=[f"Điều {number} BLHS" for number in re.findall(r"[Đđ]iều\s+(\d+)", question)],
            substances=find_substances(question), all=all_penalties,
            pcmt='luật phòng' in question.lower() and 'chống ma túy' in question.lower(),
            named=bool(named_ids),
        )
        for clause in clauses + direct:
            text = clause['text']
            if clause['title'].startswith('Tội '):
                # Keep the penalty and relevant substance thresholds rather than every unrelated point.
                paragraphs = re.split(r'\n\s*\n', text)
                relevant = clause.get('substances', find_substances(question))
                selected = [part for part in paragraphs[1:] if
                            any(substance.lower() in part.lower() for substance in relevant)
                            or 'có 02 chất ma túy' in part.lower()]
                text = '\n'.join([paragraphs[0]] + selected)
            facts.append(f"[{clause['article_id']} - {clause['title']}] khoản {clause['number']}: {text}")
        facts.extend(person_facts)
        facts.extend(edges)
        # Bound total text as well as fact count; long legal facts can exceed free-tier API limits.
        result, characters = [], 0
        for fact in dict.fromkeys(facts):
            if characters + len(fact) > 9000:
                continue
            result.append(fact)
            characters += len(fact)
            if len(result) >= max_facts:
                break
        return result

# ---------------------------------------------------------------------------------------------- KG-2

def build_graph(graph: Neo4jGraph, law_docs: list[Document], news_docs: list[Document],
                llm_fn: Callable[..., str]) -> None:
    """Load both KBs into an empty graph. llm_fn(prompt, json_mode=False) -> str (metered OpenAI chat)."""
    graph.suggested_constraints()
    articles = [parse_law_article(doc) for doc in law_docs]
    for article in articles:
        graph.add_law_article(article)
    crimes = sorted({article["crime"] for article in articles if article["crime"]})
    for doc in news_docs:
        for case in extract_news_cases(doc, lambda prompt: llm_fn(prompt, json_mode=True), crimes):
            graph.add_news_case(case, doc)

